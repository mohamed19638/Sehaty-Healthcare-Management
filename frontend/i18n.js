  const browserAlert = window.alert.bind(window);
  const browserConfirm = window.confirm.bind(window);
  window.alert = (message) => browserAlert(translate(String(message)));
  window.confirm = (message) => browserConfirm(translate(String(message)));
  document.addEventListener("DOMContentLoaded", () => applyLanguage());
  new MutationObserver((changes) => {
    for (const change of changes) {
      for (const node of change.addedNodes) {
        if (node.nodeType === Node.ELEMENT_NODE) applyLanguage(node);
        else if (node.nodeType === Node.TEXT_NODE && node.parentElement) {
          const next = translate(node.nodeValue || "");
          if (next !== node.nodeValue) node.nodeValue = next;
        }
      }
    }
  }).observe(document.body, { childList: true, subtree: true });
  applyLanguage();
